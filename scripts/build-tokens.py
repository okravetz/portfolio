#!/usr/bin/env python3
"""Generate _sass/_tokens.scss (CSS custom properties) from design/tokens.json.

design/tokens.json is a copy of the "Oren Kravetz" design system's tokens.json.
To update the site's tokens, replace that file and run:

    python3 scripts/build-tokens.py

The generated file is committed because GitHub Pages can't run this script.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "tokens.json"
OUT = ROOT / "_sass" / "_tokens.scss"


def value(raw):
    """Turn a token value into CSS: "{name}" becomes var(--name)."""
    return re.sub(r"\{([\w-]+)\}", r"var(--\1)", raw)


def main():
    data = json.loads(SRC.read_text())
    light, dark, static = [], [], []

    for t in data["color"]["tokens"]:
        lv, dv = value(t["value"]["light"]), value(t["value"]["dark"])
        light.append((t["name"], lv))
        if dv != lv:
            dark.append((t["name"], dv))

    for group in ("spacing", "radius", "shadow", "layout"):
        for t in data[group]["tokens"]:
            static.append((t["name"], t["value"]))

    for name, stack in data["type"]["families"].items():
        static.append((f"font-{name}", stack))

    for group in data["type"]["groups"]:
        for s in group["styles"]:
            n = s["name"]
            static.append((f"{n}-size", s["fontSize"]))
            static.append((f"{n}-line", str(s["lineHeight"])))
            static.append((f"{n}-weight", str(s["fontWeight"])))
            if "letterSpacing" in s:
                static.append((f"{n}-tracking", s["letterSpacing"]))

    def block(items, indent):
        pad = " " * indent
        return "".join(f"{pad}--{n}: {v};\n" for n, v in items)

    out = (
        "// Generated by scripts/build-tokens.py from design/tokens.json. Don't edit by hand.\n"
        f"// {data['name']} design system, version {data['version']}.\n\n"
        "@mixin dark-tokens {\n"
        "  color-scheme: dark;\n"
        f"{block(dark, 2)}"
        "}\n\n"
        ":root {\n"
        "  color-scheme: light;\n"
        f"{block(light, 2)}\n"
        f"{block(static, 2)}"
        "}\n\n"
        "// Dark follows the system unless the visitor picked a theme with the toggle.\n"
        "@media (prefers-color-scheme: dark) {\n"
        "  :root:not([data-theme=\"light\"]) {\n"
        "    @include dark-tokens;\n"
        "  }\n"
        "}\n\n"
        ":root[data-theme=\"dark\"] {\n"
        "  @include dark-tokens;\n"
        "}\n"
    )
    OUT.write_text(out)
    print(f"{OUT.relative_to(ROOT)}: {len(light)} colors ({len(dark)} differ in dark), {len(static)} other tokens")


if __name__ == "__main__":
    main()
